"""
gen_minitel_font.py - Emit the Minitel glyphs that are NOT plain ASCII,
as 8 x 10 bitmaps, for the Suite's Minitel videotex renderer.

Part of the Montreal Greek Times Unicorn Suite.
Copyright (C) 2026 Dimitri Papadopoulos and The Montreal Greek Times
Licensed under the GNU Affero General Public License v3.0 or later.

WHAT THIS COVERS AND WHAT IT DOES NOT.  The ASCII cells of the Minitel G0
set are drawn with the Suite's existing 5 x 7 glyphs (naplps_font_data.c,
generated by gen_naplps_font.py), reused unchanged.  STUM1B p30 asks for
exactly that shape: "Un caractere est en general represente dans une
matrice de 5 points sur 7 lignes", inside an 8 x 10 cell.  This file adds
only what ASCII does not have:

  * the SEVEN G0 cells that are not ASCII on a Minitel (schema 2.5,
    printed p100): 0x5C a diagonal, 0x5E an up arrow, 0x60 a horizontal
    bar, 0x7B 0x7C 0x7D three vertical bars, 0x7E a horizontal bar.
    They are JOINTIVE (p30: bars, diagonals and arrows fill the width or
    height of the cell so that neighbours join), so they are drawn on the
    full 8 x 10 cell, not in the 5 x 7 box.  Their positions were MEASURED
    on the 300 dpi page image of the scan (docs/2026-09-27_SUITE_MINITEL_
    MODE.md section 2): verticals at 0.16, 0.51 and 0.86 of the cell width
    (dots 1, 4 and 6), horizontals at 0.15 and 0.52 of its height (lines 1
    and 5).  The median bars are the ones p30 says the arrows align with.
  * a MINIMAL G2 (schema 2.8, VGP5, printed p103): pound, section,
    four arrows, degree, plus-minus, divide, three fractions, OE and oe,
    beta, and the fifteen accented lower-case letters of p90;
  * the FULL BLOCK (DEL in code, p98, and the error symbol, p99) and the
    LOW BAR shown for an SS2 code outside the repertoire (p90).

The glyph SHAPES are ORIGINAL WORK drawn for this project.  The accented
letters reuse this project's own lower-case bodies from
gen_naplps_font.py (imported, not copied) with accents drawn here.
Nothing is copied from any font file, package, web source or Minitel
implementation.

  usage: python tools/gen_minitel_font.py src/minitel_font_data.c

Each glyph is ten strings of eight characters, '#' on and '.' off, row 0
the TOP.  In the emitted C table each glyph is ten bytes, one per scan
line, top first, BIT 0 THE LEFTMOST dot, the convention of
rip_font8x8.h and naplps_font.h.

The ORDER of EXT below must match the MT_G_* enum in minitel_decode.h,
starting at MT_G_FULLBLOCK = 0x80.  The generator checks the count.
"""

import os
import sys

sys.dont_write_bytecode = True     # leave no __pycache__ in tools/
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_naplps_font as naplps  # noqa: E402  (the project's own 5x7 art)

W, H = 8, 10
BOX_X, BOX_Y = 1, 1       # where a 5 x 7 glyph sits in the 8 x 10 cell


def blank():
    return [['.'] * W for _ in range(H)]


def from_5x7(rows5):
    g = blank()
    for y, row in enumerate(rows5):
        for x, px in enumerate(row):
            if px == '#':
                g[BOX_Y + y][BOX_X + x] = '#'
    return g


def art(rows):
    assert len(rows) == H, rows
    for r in rows:
        assert len(r) == W and set(r) <= set('#.'), r
    return [list(r) for r in rows]


def box(rows7):
    """A 5 x 7 glyph drawn here, placed like the ASCII ones."""
    assert len(rows7) == 7 and all(len(r) == 5 for r in rows7), rows7
    return from_5x7(rows7)


# ---------------------------------------------------------------------------
# Accents, drawn in rows 0 and 1 of the 5 x 7 box, over a lower-case body
# that occupies rows 2 to 6 (gen_naplps_font's x-height).  The i body is
# the dotless one: its own row-0 dot is replaced by the accent.
# ---------------------------------------------------------------------------

ACCENT = {
    'grave': ['.#...', '..#..'],
    'acute': ['...#.', '..#..'],
    'circ':  ['..#..', '.#.#.'],
    'diaer': ['.#.#.', '.....'],
}


def accented(base, accent):
    body = [list(r) for r in naplps.GLYPHS[base]]
    body[0] = list('.....')
    body[1] = list('.....')
    top = ACCENT[accent]
    for y in range(2):
        for x in range(5):
            if top[y][x] == '#':
                body[y][x] = '#'
    return from_5x7([''.join(r) for r in body])


def cedilla():
    g = from_5x7(naplps.GLYPHS['c'])
    # The c's bottom stroke is on box row 6 (cell line 7); the cedilla
    # hangs from its middle into lines 8 and 9, below the box.
    g[8][3] = '#'
    g[9][2] = '#'
    g[9][3] = '#'
    return g


# ---------------------------------------------------------------------------
