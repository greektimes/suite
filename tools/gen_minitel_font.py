EXPECTED_EXT = 32   # MT_G_END - MT_G_FULLBLOCK in minitel_decode.h

# ---------------------------------------------------------------------------
# The seven G0 cells that are not ASCII on a Minitel, jointive, in code
# order 0x5C 0x5E 0x60 0x7B 0x7C 0x7D 0x7E.
# ---------------------------------------------------------------------------

def vbar(x):
    g = blank()
    for y in range(H):
        g[y][x] = '#'
    return g


def hbar(y):
    g = blank()
    for x in range(W):
        g[y][x] = '#'
    return g


def diagonal():
    # Top-left to bottom-right across the whole cell, as drawn at 5/C.
    g = blank()
    for y in range(H):
        x = (y * (W - 1) + (H - 1) // 2) // (H - 1)
        g[y][x] = '#'
    return g


def up_arrow():
    g = vbar(4)
    g[1][3] = g[1][5] = '#'
    g[2][2] = g[2][6] = '#'
    return g


G0_SPECIAL = [
    (0x5C, 'diagonal', diagonal()),
    (0x5E, 'up arrow', up_arrow()),
    (0x60, 'median horizontal bar', hbar(5)),
    (0x7B, 'left vertical bar', vbar(1)),
    (0x7C, 'median vertical bar', vbar(4)),
    (0x7D, 'right vertical bar', vbar(6)),
    (0x7E, 'upper horizontal bar', hbar(1)),
]


def to_bytes(g):
    out = []
    for row in g:
        v = 0
        for x, px in enumerate(row):
            if px == '#':
                v |= 1 << x
        out.append(v)
    return out


def main():
    if len(EXT) != EXPECTED_EXT:
        sys.stderr.write("EXT has %d glyphs, the enum expects %d\n"
                         % (len(EXT), EXPECTED_EXT))
        return 1
    for name, g in EXT:
        if len(g) != H or any(len(r) != W for r in g):
            sys.stderr.write("bad glyph %s\n" % name)
            return 1

    out = []
    w = out.append
    w("/*")
    w(" * minitel_font_data.c - 8 x 10 glyphs for the Minitel renderer's")
    w(" *                       non-ASCII cells.  GENERATED, do not edit.")
