# Build-time only. Turns "Modern DOS" 8x16 and 8x8 (Jayvee Enaguas, CC0 1.0)
# into src/gwb_font8x16.h and src/gwb_font8x8.h for the GW-BASIC tab: the
# 8x16 face draws text mode, the 8x8 face draws characters in the CGA
# graphics modes and fills the ROM font table at F000:FA6E. The font is drawn
# as one square contour per pixel, so sampling each pixel centre with a
# point-in-outline test reproduces the bitmap exactly; no hinting, no
# anti-aliasing, no guessing.
#
#     python tools/font_ttf_to_cp437.py ModernDOS8x16.ttf src/gwb_font8x16.h 16
#     python tools/font_ttf_to_cp437.py ModernDOS8x8.ttf  src/gwb_font8x8.h  8
#
# Needs fontTools (pip install fonttools). Prints a coverage report and
# exits non-zero if any CP437 code point the screen can show is missing.

import sys
from fontTools.ttLib import TTFont
from fontTools.pens.pointInsidePen import PointInsidePen

# IBM's glyphs for the control range, which a PC shows as pictures.
LOW = [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
       0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
       0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
       0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]


def cp437_to_unicode(code):
    if code < 0x20:
        return LOW[code]
    if code == 0x7F:
        return 0x2302                 # house
    if code == 0xFF:
        return 0x00A0                 # no-break space, drawn blank
    return ord(bytes([code]).decode("cp437"))


def main():
    src, dst = sys.argv[1], sys.argv[2]
    h = int(sys.argv[3]) if len(sys.argv) > 3 else 16
    name = "gwb_font8x%d" % h
    guard = name.upper() + "_H"
    font = TTFont(src)
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    upm = font["head"].unitsPerEm
    asc = font["hhea"].ascent
    desc = font["hhea"].descent
    px = (asc - desc) / float(h)      # font units per pixel row
    adv = font["hmtx"][cmap[ord("A")]][0]
    if abs(adv / px - 8) > 0.01:
        sys.exit("advance is %.2f px, expected 8" % (adv / px))

    rows = []
    missing = []
    for code in range(256):
        uc = cp437_to_unicode(code)
        glyph = cmap.get(uc) if uc else None
        bits = [0] * h
        if uc in (0, 0x00A0, 0x20):
            pass                       # blank by definition
        elif glyph is None:
            missing.append((code, uc))
        else:
            for y in range(h):
                fy = asc - (y + 0.5) * px
                b = 0
                for x in range(8):
                    pen = PointInsidePen(gs, ((x + 0.5) * px, fy))
                    gs[glyph].draw(pen)
                    if pen.getResult():
                        b |= 0x80 >> x
                bits[y] = b
        rows.append(bits)

    print("units/em %d, ascent %d, descent %d, %.1f units per pixel"
          % (upm, asc, desc, px))
    print("missing CP437 glyphs: %d" % len(missing))
    for code, uc in missing:
        print("  0x%02X -> U+%04X" % (code, uc))

    with open(dst, "w", newline="\n") as f:
        f.write(("/* %s.h - CP437 8x%d screen font for the GW-BASIC tab.\n"
                 " *\n"
                 " * GENERATED by tools/font_ttf_to_cp437.py from %s,\n"
                 " * \"Modern DOS\" by Jayvee Enaguas (HarvettFox96), released under\n"
                 " * Creative Commons Zero (CC0) 1.0. See licenses/LICENSE.moderndos.txt.\n"
                 " * Do not edit by hand; regenerate instead.\n"
                 " *\n"
                 " * One byte per pixel row, most significant bit leftmost.\n"
                 " */\n\n"
                 "#ifndef %s\n#define %s\n\n"
                 "static const unsigned char %s[256][%d] = {\n")
                % (name, h, src.replace("\\", "/").split("/")[-1],
                   guard, guard, name, h))
        for code, bits in enumerate(rows):
            f.write("    { " + ", ".join("0x%02X" % b for b in bits)
                    + " }, /* 0x%02X */\n" % code)
        f.write("};\n\n#endif /* %s */\n" % guard)

    for code in (0x41, 0x1B, 0xC9, 0xB0):
        print("glyph 0x%02X:" % code)
        for b in rows[code]:
            print("   " + "".join("#" if b & (0x80 >> i) else "." for i in range(8)))
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
